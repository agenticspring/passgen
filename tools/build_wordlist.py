def main() -> int:
    raw = [w.strip() for w in RAW.splitlines() if w.strip()]
    words = sorted({w for w in raw})
    bad = [w for w in words if not (w.isalpha() and w.islower())]
    if bad:
        print("non-lowercase-alpha words:", bad[:20], file=sys.stderr)
        return 1
    if len(words) < 1024:
        print(f"only {len(words)} unique words, need >= 1024", file=sys.stderr)
        return 1
    out = Path(__file__).resolve().parent.parent / "words.txt"
    out.write_text("\n".join(words) + "\n", encoding="utf-8")
    print(f"wrote {out} with {len(words)} words")
    return 0

if __name__ == "__main__":
    sys.exit(main())
